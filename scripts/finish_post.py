#!/usr/bin/env python3
"""Make sure a blog post is a complete page.

Posts generated by the pipeline can be cut off when the model hits its
output limit, which drops the end of the article, the affiliate
disclosure, the site footer and main.js. This script:

  1. leaves complete posts (ending in </html>) untouched,
  2. otherwise trims back to the last complete block element,
  3. closes any open tags, adding the affiliate disclosure at the end of
     the <article> if it isn't already there,
  4. appends the standard site footer (which also carries the
     disclosure), main.js and </body></html>.

Usage: python3 scripts/finish_post.py blog/some-post.html [more.html ...]
Prints one line per file: OK (already complete) or FIXED.
"""
import os
import re
import sys
from html.parser import HTMLParser

HERE = os.path.dirname(os.path.abspath(__file__))
FOOTER = open(os.path.join(HERE, "post_footer.html")).read().rstrip()

DISCLOSURE = (
    '\n        <div class="post-disclosure" style="margin-top: 2.5rem; padding-top: 2rem; '
    'border-top: 1px solid var(--gray-200);">\n'
    '          <p style="font-size: .875rem; color: var(--gray-500);"><em>Disclosure: '
    "As an Amazon Associate, EcoThrift Home earns from qualifying purchases. "
    "This doesn't change the price you pay.</em></p>\n"
    "        </div>\n"
)

# Block-level closing tags that are safe places to cut a truncated page.
SAFE_CUT = re.compile(
    r"</(?:p|li|ul|ol|div|table|tbody|thead|tr|h[1-6]|blockquote|section|aside|figure|nav|details)>",
    re.I,
)
VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link",
        "meta", "source", "track", "wbr"}


class OpenTags(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.stack = []

    def handle_starttag(self, tag, attrs):
        if tag not in VOID:
            self.stack.append(tag)

    def handle_startendtag(self, tag, attrs):
        pass

    def handle_endtag(self, tag):
        if tag in self.stack:
            # pop up to and including the matching tag (tolerates sloppy HTML)
            while self.stack:
                if self.stack.pop() == tag:
                    break


def finish(html):
    if html.rstrip().lower().endswith("</html>"):
        return html, False

    # Cut back to the last complete block element.
    last = None
    for last in SAFE_CUT.finditer(html):
        pass
    if last is None:
        raise ValueError("no safe cut point found")
    body = html[: last.end()]
    # Don't leave a dangling heading whose section was cut off.
    while True:
        m = re.search(r"\s*<h[2-6][^>]*>.*?</h[2-6]>\s*$", body, re.S | re.I)
        if not m or "<p" in m.group(0):
            break
        body = body[: m.start()]

    p = OpenTags()
    p.feed(body)
    stack = p.stack

    article_has_disclosure = False
    a = body.rfind("<article")
    if a != -1 and re.search(r"as an amazon associate", body[a:], re.I):
        article_has_disclosure = True

    tail = []
    while stack and stack[-1] not in ("body", "html"):
        tag = stack.pop()
        if tag == "article" and not article_has_disclosure:
            tail.append(DISCLOSURE)
        tail.append(f"</{tag}>")
    out = body + "\n" + "\n".join(tail) + "\n\n  <!-- FOOTER -->\n" + FOOTER + \
        '\n\n  <script src="../js/main.js"></script>\n</body>\n</html>\n'
    return out, True


def main(paths):
    for path in paths:
        html = open(path, encoding="utf-8").read()
        new, changed = finish(html)
        if changed:
            open(path, "w", encoding="utf-8").write(new)
        print(("FIXED " if changed else "OK    ") + path)


if __name__ == "__main__":
    main(sys.argv[1:])
